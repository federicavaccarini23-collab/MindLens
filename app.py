# RESPONSE CLEANING
# ============================================================

def clean_response(text):
    """
    Clean accidental formatting placeholders generated by the model.

    This prevents internal formatting instructions such as:
    [line break], [linebreak], <br>, etc. from appearing
    in the user-facing response.
    """

    if not text:
        return ""

    cleaned = text

    # Exact formatting placeholders
    placeholders = [
        "[line break]",
        "[linebreak]",
        "[LINE BREAK]",
        "[LINEBREAK]",
        "[Line Break]",
        "[Linebreak]",
        "<br>",
        "<br/>",
        "<br />",
        "<BR>",
        "<BR/>",
        "<BR />",
    ]

    for placeholder in placeholders:
        cleaned = cleaned.replace(placeholder, "\n")

    # Convert literal escaped newlines into actual newlines
    cleaned = cleaned.replace("\\n", "\n")

    # Remove accidental markdown-style formatting placeholders
    cleaned = re.sub(
        r"\[\s*line\s*break\s*\]",
        "\n",
        cleaned,
        flags=re.IGNORECASE
    )

    # Remove HTML break tags with optional spaces
    cleaned = re.sub(
        r"<\s*br\s*/?\s*>",
        "\n",
        cleaned,
        flags=re.IGNORECASE
    )

    # Remove excessive blank lines
    cleaned = re.sub(r"\n{3,}", "\n\n", cleaned)

    return cleaned.strip()


